# apps
# --------------------------------------------------------------------------

def section_header(ctx: ReportContext) -> List[str]:
    """Title, machine line and provenance note."""
    host = ctx.snap["host"]
    return [
        f"# Mac inventory — {host['computer_name']}\n",
        f"{host['model']} · {host['chip']} · macOS {host['macos']} · set up {fmt_date(host.get('setup_date'))} · "
        f"collected {host['collected_at'][:16].replace('T', ' ')} UTC\n",
        "Generated by `mise run mac:inventory` (setup/inventory/mac_inventory.py). "
        "Read-only: nothing was installed or removed.\n",
    ]


def section_summary(ctx: ReportContext) -> List[str]:
    """Headline counts."""
    by_source: Dict[str, int] = {}
    for app in ctx.snap["apps"]:
        by_source[app["source"]] = by_source.get(app["source"], 0) + 1
    rows = [
        ["Apps (non-Apple)", len(ctx.snap["apps"]) - len(ctx.buckets["apple"])],
        ["… installed by Homebrew cask", by_source.get("cask", 0)],
        ["… from the Mac App Store", by_source.get("mas", 0)],
        ["… installed manually (no package manager)", by_source.get("manual", 0)],
        [f"Apps not used in {ctx.stale_days}+ days (removal candidates)", len(ctx.buckets["stale"])],
        ["Homebrew formulae you installed (leaves)", len(ctx.brew.get("leaves", []))],
        ["Homebrew casks", len(ctx.brew.get("casks", []))],
        ["mise tools active", len(ctx.active_tools)],
        ["mise tool versions nothing uses (`mise prune`)", len(ctx.mise.get("prunable", []))],
    ]
    return ["## Summary\n", md_table(["", "Count"], rows)]


def section_removal_candidates(ctx: ReportContext) -> List[str]:
    """Apps with no sign of use within the stale window."""
    apps = sorted(ctx.buckets["stale"], key=lambda a: max(a["last_used"] or "", a["activity"] or ""))
    rows = [[a["name"], app_install_ref(a), f"{fmt_date(a['last_used'])} ({fmt_age(a['last_used'])})",
             fmt_date(a["activity"]), a["size_mb"]] for a in apps]
    return [
        f"## Removal candidates: apps not used in {ctx.stale_days}+ days\n",
        "*Last opened* is Spotlight's launch record (`kMDItemLastUsedDate`). Some apps are never "
        "recorded (menu-bar agents, apps started by other apps or by JetBrains Toolbox), so "
        "*Data touched* adds the newest change to the app's preferences/containers: a hint of use, "
        "not proof.\n",
        md_table(["App", "Installed via", "Last opened", "Data touched", "Size MB"], rows),
    ]


def section_intel_only(ctx: ReportContext) -> List[str]:
    """Apps that still need Rosetta (only when there are any)."""
    intel = [a for a in ctx.snap["apps"] if a.get("arch") == "intel-only"]
    if not intel:
        return []
    return ["## Intel-only apps (run under Rosetta)\n",
            md_table(["App", "Installed via"], [[a["name"], app_install_ref(a)] for a in intel])]


def section_apps_in_use(ctx: ReportContext) -> List[str]:
    """Apps with evidence of use, and what that evidence is."""
    apps = sorted(ctx.buckets["active"], key=lambda a: a["name"].lower())
    return [f"## Apps in use (opened within {ctx.stale_days} days, or a login item)\n",
            md_table(["App", "Installed via", "Why"], [[a["name"], app_install_ref(a), a["evidence"]] for a in apps])]


# --------------------------------------------------------------------------
# duplicates, ghosts, cleanup
# --------------------------------------------------------------------------

def duplicate_row(ctx: ReportContext, formula: Json) -> Optional[List[str]]:
    """Table row for a formula whose commands a mise tool also provides."""
    shared = sorted(set(formula["bins"]) & set(ctx.mise_bins))
    if not shared:
        return None
    tools = ", ".join(sorted({ctx.mise_bins[b] for b in shared}))
    commands = ", ".join(shared[:4]) + (" …" if len(shared) > 4 else "")
    return [f"`{formula['full_name']}`", tools, commands]


def section_duplicates(ctx: ReportContext) -> List[str]:
    """Homebrew formulae that duplicate a mise tool."""
    rows = [r for r in (duplicate_row(ctx, f) for f in ctx.leaf_formulae) if r]
    return [
        "## Homebrew formulae duplicated by a mise tool\n",
        "Both Homebrew and mise put these commands on PATH. mise wins when it is activated, so the "
        "Homebrew copy is usually dead weight — but check nothing launched outside your shell "
        "(GUI apps, launchd jobs) relies on the `/opt/homebrew/bin` copy first.\n",
        md_table(["Homebrew formula", "mise tool", "Shared commands"], rows),
    ]


def section_ghost_casks(ctx: ReportContext) -> List[str]:
    """Casks Homebrew still lists although the app was deleted."""
    rows = [[f"`{c['full_token']}`", ", ".join(c["apps"])] for c in ctx.ghost_casks()]
    return [
        "## Ghost casks: Homebrew still lists them, but the app is gone\n",
        "The app was deleted by hand, so Homebrew's record is stale (and a declared one would be "
        "reinstalled on the next `mise bootstrap`).\n",
        md_table(["Cask", "Expected app"], rows),
    ]


def cleanup_commands(ctx: ReportContext) -> List[str]:
    """Shell commands for the mechanical cleanups only."""
    commands = []
    duplicates = sorted(f["full_name"] for f in ctx.leaf_formulae if ctx.shares_mise_bin(f))
    ghosts = sorted(c["token"] for c in ctx.ghost_casks())
    if duplicates:
        commands.append("brew uninstall " + " ".join(duplicates))
    if ghosts:
        commands.append("brew uninstall --cask " + " ".join(ghosts))
    if ctx.mise.get("prunable"):
        commands.append("mise prune")
    return commands


def section_cleanup(ctx: ReportContext) -> List[str]:
    """Review-first cleanup commands."""
    body = "\n".join(cleanup_commands(ctx)) or "# nothing to clean up"
    return [
        "## Cleanup commands (review before running)\n",
        "Only the mechanical cases: Homebrew copies of tools mise already provides, stale cask "
        "records, and old mise tool versions. Everything else above is a judgement call.\n",
        "```sh\n" + body + "\n```\n",
    ]


# --------------------------------------------------------------------------
# CLI usage
# --------------------------------------------------------------------------

def formula_names(formula: Json) -> Set[str]:
    """Commands a formula links, or its name when it links none."""
    return set(formula["bins"]) or {formula["name"]}


def tool_names(tool: Json) -> Set[str]:
    """Commands a mise tool provides, or its short name."""
    return set(tool["bins"]) or {tool_short_name(tool["name"])}


def never_used(ctx: ReportContext, names: Set[str], own_name: str) -> bool:
    """No history hits and not run by shell init files."""
    total, _, _ = cli_last_use(ctx.usage, names)
    return total == 0 and not (names | {own_name}) & ctx.shell_init


def section_unused_formulae(ctx: ReportContext) -> List[str]:
    """Formulae never typed in any shell history."""
    note = (f"Usage counts come from shell history (zsh with timestamps; PowerShell without — "
            f"*recent pwsh* counts its last 3,000 commands, history file last written "
            f"{fmt_date(ctx.pwsh_mtime)}). A tool used "
            "only by scripts or other tools will look unused. Tools your shell init files reference "
            "(starship, zoxide, direnv, zsh plugins …) are left out.\n")
    rows = [[f"`{f['full_name']}`", (f.get("desc") or "")[:70], ", ".join(sorted(formula_names(f))[:3])]
            for f in sorted(ctx.leaf_formulae, key=lambda f: f["name"])
            if never_used(ctx, formula_names(f), f["name"])]
    return ["## Homebrew formulae never seen in shell history\n", note,
            md_table(["Formula", "Description", "Commands"], rows)]


def section_unused_tools(ctx: ReportContext) -> List[str]:
    """Active mise tools never typed in any shell history."""
    rows = [[f"`{t['name']}`", t["version"], (t.get("source") or "").replace(str(HOME), "~")]
            for t in sorted(ctx.active_tools, key=lambda t: t["name"])
            if never_used(ctx, tool_names(t), tool_short_name(t["name"]))]
    return ["## mise tools never seen in shell history\n", md_table(["Tool", "Version", "Declared in"], rows)]


def usage_candidates(ctx: ReportContext) -> List[Tuple[str, Set[str]]]:
    """(label, command names) for every brew leaf and active mise tool."""
    labelled = [(f"brew `{f['name']}`", formula_names(f)) for f in ctx.leaf_formulae]
    return labelled + [(f"mise `{t['name']}`", tool_names(t)) for t in ctx.active_tools]


def section_cli_usage(ctx: ReportContext) -> List[str]:
    """History hits per tool, oldest last-use first."""
    rows = []
    seen: Set[str] = set()
    for label, names in usage_candidates(ctx):
        total, recent, last = cli_last_use(ctx.usage, names)
        if total and label not in seen:
            seen.add(label)
            rows.append([label, total, recent, fmt_date(last)])
    rows.sort(key=lambda r: (r[3] if r[3] != "—" else "", r[1]))
    return ["## CLI usage (Homebrew leaves + mise tools)\n",
            md_table(["Tool", "History hits", "Recent pwsh hits", "Last zsh use"], rows)]


