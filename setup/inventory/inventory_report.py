# drift
# --------------------------------------------------------------------------

def declared_cli_names(declared: Declared) -> Set[str]:
    """Command/formula names the config covers, including mise aliases."""
    tools = declared["tools"]
    # brew's own mise formula is installed by setup/setup-macos.sh before mise exists.
    return tools | {TOOL_ALIASES.get(t, t) for t in tools} | declared["brew"] | {"mise"}


def undeclared_formula_rows(ctx: ReportContext, declared: Declared) -> List[List[str]]:
    """Rows for leaf formulae nothing in the config declares."""
    covered = declared_cli_names(declared)
    rows = []
    for formula in sorted(ctx.leaf_formulae, key=lambda f: f["name"]):
        if formula["name"] in covered or formula["full_name"].split("/")[-1] in covered:
            continue
        hint = "yes — drop the brew copy" if ctx.shares_mise_bin(formula) else ""
        rows.append([f"`{formula['full_name']}`", hint, (formula.get("desc") or "")[:70]])
    return rows


def undeclared_cask_rows(ctx: ReportContext, declared: Declared) -> List[List[str]]:
    """Rows for installed casks nothing in the config declares."""
    return [[f"`{c['full_token']}`", ", ".join(c["apps"]) or "—"]
            for c in sorted(ctx.brew.get("casks", []), key=lambda c: c["token"])
            if c["token"] not in declared["brew-cask"]]


def undeclared_mas_rows(ctx: ReportContext, declared: Declared) -> List[List[str]]:
    """Rows for App Store apps nothing in the config declares."""
    return [[m["name"], f"`mas:{m['id']}`"] for m in ctx.snap.get("mas", []) if m["id"] not in declared["mas"]]


def manual_app_rows(ctx: ReportContext) -> List[List[str]]:
    """Rows for apps no package manager installed."""
    return [[a["name"], a["bundle_id"] or "—", fmt_date(a["last_used"])]
            for a in sorted(ctx.snap["apps"], key=lambda a: a["name"].lower()) if a["source"] == "manual"]


def section_drift_installed(ctx: ReportContext, declared: Declared) -> List[str]:
    """Installed software the config doesn't declare."""
    casks = undeclared_cask_rows(ctx, declared)
    mas = undeclared_mas_rows(ctx, declared)
    manual = manual_app_rows(ctx)
    return [
        "## Drift: installed but not declared in dotfiles\n",
        "Not reproduced on a new machine. Either declare it (`mise bootstrap packages use -g …` / "
        "`mise use -g …`) or remove it.\n",
        "### Homebrew formulae\n",
        md_table(["Formula", "Also a mise tool?", "Description"], undeclared_formula_rows(ctx, declared)),
        "### Casks\n", md_table(["Cask", "Apps"], casks),
        "### Mac App Store\n", md_table(["App", "ID"], mas),
        "### Apps installed manually (no package manager)\n",
        "Check `brew search --cask <name>`; many of these have a cask, which makes them reproducible.\n",
        md_table(["App", "Bundle ID", "Last used"], manual),
    ]


def section_drift_declared(ctx: ReportContext, declared: Declared) -> List[str]:
    """Declared packages this Mac doesn't have."""
    casks = {c["token"] for c in ctx.brew.get("casks", [])}
    mas = {m["id"] for m in ctx.snap.get("mas", [])}
    formulae = {f["name"] for f in ctx.brew.get("formulae", [])}
    rows = [[f"`brew-cask:{c}`"] for c in sorted(declared["brew-cask"] - casks)]
    rows += [[f"`mas:{m}`"] for m in sorted(declared["mas"] - mas)]
    rows += [[f"`brew:{b}`"] for b in sorted(declared["brew"] - formulae)]
    return ["## Drift: declared in dotfiles but not installed\n", md_table(["Package"], rows)]


def section_drift(ctx: ReportContext) -> List[str]:
    """Both drift directions; skipped when the config couldn't be read."""
    if ctx.declared is None:
        return []
    return section_drift_installed(ctx, ctx.declared) + section_drift_declared(ctx, ctx.declared)


# --------------------------------------------------------------------------
# other managers, startup, housekeeping
