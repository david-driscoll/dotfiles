"""
Turn one inventory snapshot into a Markdown report.

Sections: removal candidates, apps in use, Homebrew/mise duplicates, ghost
casks, cleanup commands, CLI tools missing from shell history, drift against
the dotfiles' mise config, other package managers, startup items.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Set, Tuple

from inventory_common import (
    HOME, TOOL_ALIASES, Declared, Json, app_install_ref, classify_apps, cli_last_use,
    fmt_age, fmt_date, md_table, shorten, tool_short_name,
)

OTHER_MANAGER_ROUTES = (
    ("npm_global", "npm -g", "`npm:<pkg>` in mise [tools]"),
    ("volta", "Volta", "mise already manages node; move packages to `npm:<pkg>`"),
    ("uv_tools", "uv tool", "`pipx:<pkg>` (mise uses uv for it)"),
    ("pipx", "pipx", "`pipx:<pkg>`"),
    ("dotnet_tools", "dotnet tool -g", "`dotnet:<pkg>`"),
    ("go_bin", "~/go/bin", "`go:<module>`"),
    ("cargo_bin", "~/.cargo/bin", "`cargo:<crate>` (rustup proxies are expected)"),
    ("krew", "kubectl krew", "keep krew, or `aqua:`/`github:` per plugin"),
    ("gh_extensions", "gh extensions", "installed by .config/mise/scripts/gh-extensions.ps1"),
    ("vscode_extensions", "VS Code extensions", "VS Code Settings Sync"),
    ("vscode_insiders_extensions", "VS Code Insiders extensions", "VS Code Settings Sync"),
)


class ReportContext:
    """Everything the report sections share, computed once."""

    def __init__(self, snap: Json, declared: Optional[Declared], stale_days: int) -> None:
        """Index the snapshot for the report sections."""
        self.snap = snap
        self.declared = declared
        self.stale_days = stale_days
        self.brew: Json = snap.get("brew", {})
        self.mise: Json = snap.get("mise", {})
        shell_usage = snap.get("shell_usage", {})
        self.usage: Json = shell_usage.get("commands", {})
        self.shell_init: Set[str] = set(shell_usage.get("shell_init_words", []))
        self.pwsh_mtime: Optional[str] = shell_usage.get("pwsh_history_mtime")
        self.buckets = classify_apps(snap["apps"], stale_days)
        self.active_tools = [t for t in self.mise.get("tools", []) if t["active"]]
        self.mise_bins = self._mise_bins()
        leaves = set(self.brew.get("leaves", []))
        self.leaf_formulae = [f for f in self.brew.get("formulae", [])
                              if f["name"] in leaves or f["full_name"] in leaves]

    def _mise_bins(self) -> Dict[str, str]:
        bins: Dict[str, str] = {}
        for tool in self.active_tools:
            for name in tool["bins"]:
                bins.setdefault(name, tool["name"])
        return bins

    def shares_mise_bin(self, formula: Json) -> bool:
        """True when a formula links a command a mise tool also provides."""
        return bool(set(formula["bins"]) & set(self.mise_bins))

    def ghost_casks(self) -> List[Json]:
        """Casks with app artifacts whose apps are no longer on disk."""
        present = {a["cask"] for a in self.snap["apps"] if a.get("cask")}
        return [c for c in self.brew.get("casks", []) if c["apps"] and c["token"] not in present]


