def section_other_managers(ctx: ReportContext) -> List[str]:
    """Global packages outside Homebrew/mise and where they could go."""
    other = ctx.snap.get("other", {})
    rows = [[label, len(other[key]), shorten(other[key]), hint]
            for key, label, hint in OTHER_MANAGER_ROUTES if other.get(key)]
    if other.get("conda"):
        rows.append(["conda", "—", "miniconda/anaconda directory present", "uv/mise python replace this"])
    return [
        "## Other package managers\n",
        "Tools installed outside Homebrew/mise don't follow you to the other Mac. mise has backends for "
        "most of them (`npm:`, `pipx:`, `dotnet:`, `cargo:`, `go:`), so they can move into `[tools]`.\n",
        md_table(["Manager", "Count", "Packages", "mise route"], rows),
    ]


def section_startup(ctx: ReportContext) -> List[str]:
    """Login items and LaunchAgents."""
    startup = ctx.snap.get("startup", {})
    return [
        "## Startup items\n",
        "**Login items:** " + (", ".join(startup.get("login_items", [])) or "none") + "\n",
        "**~/Library/LaunchAgents:** " + (", ".join(startup.get("launch_agents", [])) or "none") + "\n",
    ]


def section_housekeeping(ctx: ReportContext) -> List[str]:
    """Old mise tool versions (only when there are any)."""
    prunable = ctx.mise.get("prunable")
    if not prunable:
        return []
    return ["## mise housekeeping\n", f"`mise prune` would remove {len(prunable)} unused tool versions.\n"]


SECTIONS = (
    section_header, section_summary, section_removal_candidates, section_intel_only,
    section_apps_in_use, section_duplicates, section_ghost_casks, section_cleanup,
    section_unused_formulae, section_unused_tools, section_cli_usage, section_drift,
    section_other_managers, section_startup, section_housekeeping,
)


def build_report(snap: Json, declared: Optional[Declared], stale_days: int) -> str:
    """Render the full Markdown report for one snapshot."""
    ctx = ReportContext(snap, declared, stale_days)
    parts: List[str] = []
    for section in SECTIONS:
        parts += section(ctx)
    return "\n".join(parts)
